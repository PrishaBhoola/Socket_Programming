#!/usr/bin/env python3
"""
Plotting and Analysis for Greedy Client FCFS Fairness (Part 3)
- Reads the 'fairness_results.csv' file generated by the experiments.
- Calculates averages and confidence intervals for the collected data.
- Generates a plot of Jain's Fairness Index vs. the greediness factor 'c'.
"""

import csv
import matplotlib.pyplot as plt
import numpy as np
import argparse
from pathlib import Path
from collections import defaultdict
import scipy.stats as st

def load_and_aggregate_results(results_file):
    """
    Loads the results from the CSV and aggregates them by the 'c' value.
    """
    if not Path(results_file).exists():
        print(f"ERROR: Results file not found at '{results_file}'.")
        print("Please run the experiments first using 'sudo python3 run_experiments.py'")
        return None

    # Use defaultdict to easily append to lists for each c_value
    results_by_c = defaultdict(lambda: {'jains_indices': [], 'advantage_ratios': []})

    with open(results_file, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                c_value = int(row['c_value'])
                jains_index = float(row['jains_fairness_index'])
                advantage_ratio = float(row['advantage_ratio'])
                
                results_by_c[c_value]['jains_indices'].append(jains_index)
                results_by_c[c_value]['advantage_ratios'].append(advantage_ratio)
            except (ValueError, KeyError) as e:
                print(f"Skipping malformed row in CSV: {row}. Error: {e}")
    
    return results_by_c

def calculate_statistics(aggregated_results):
    """
    Calculates the mean and 95% confidence interval for each 'c' value.
    """
    stats = {}
    for c_value, data in aggregated_results.items():
        jains_indices = data['jains_indices']
        
        if len(jains_indices) < 2:
            # Not enough data for a confidence interval, just use mean and 0 error
            mean = np.mean(jains_indices)
            conf_interval = (mean, mean)
        else:
            conf_interval = st.t.interval(confidence=0.95, df=len(jains_indices)-1,
                                          loc=np.mean(jains_indices),
                                          scale=st.sem(jains_indices))
        
        stats[c_value] = {
            'mean_jfi': np.mean(jains_indices),
            'jfi_ci_low': conf_interval[0],
            'jfi_ci_high': conf_interval[1],
            'y_error': np.mean(jains_indices) - conf_interval[0] # Symmetric error for plotting
        }
    return stats

def create_jains_fairness_plot(stats, output_file='p3_plot.png'):
    """
    Generates and saves the plot for Jain's Fairness Index vs. 'c'.
    """
    if not stats:
        print("No statistics to plot.")
        return

    # Sort the data by 'c' value for a clean plot
    sorted_c = sorted(stats.keys())
    mean_jfi = [stats[c]['mean_jfi'] for c in sorted_c]
    y_error = [stats[c]['y_error'] for c in sorted_c]

    plt.style.use('seaborn-v0_8-whitegrid')
    plt.figure(figsize=(10, 6))

    # Plot the data with error bars representing the 95% confidence interval
    plt.errorbar(sorted_c, mean_jfi, yerr=y_error, fmt='-o',
                 capsize=5, capthick=2, elinewidth=2, markeredgewidth=2,
                 label="Jain's Fairness Index (JFI)")

    # Add reference lines for context
    plt.axhline(y=1.0, color='green', linestyle='--', label='Perfect Fairness (JFI = 1.0)')
    plt.axhline(y=0.5, color='orange', linestyle=':', label='Fairness Threshold (JFI = 0.5)')

    # Formatting the plot
    plt.title("Fairness Analysis: Impact of a Greedy Client on FCFS", fontsize=16)
    plt.xlabel("Greediness Factor 'c' (Requests per Turn)", fontsize=12)
    plt.ylabel("Jain's Fairness Index (JFI)", fontsize=12)
    plt.xticks(sorted_c)
    plt.ylim(0, 1.1)
    plt.legend(fontsize=10)
    plt.grid(True, which='both', linestyle='-', linewidth=0.5)
    
    # Add a concluding text box
    conclusion = (
        "As the greedy client's 'c' value increases,\n"
        "the overall system fairness (JFI) drops significantly.\n"
        "This demonstrates the vulnerability of pure FCFS\n"
        "to clients that don't follow a one-request-per-turn protocol."
    )
    plt.text(0.5, 0.2, conclusion, transform=plt.gca().transAxes,
             fontsize=10, verticalalignment='bottom',
             bbox=dict(boxstyle='round,pad=0.5', fc='wheat', alpha=0.5))

    plt.tight_layout()
    plt.savefig(output_file, dpi=300)
    print(f"Plot saved successfully to '{output_file}'")

def main():
    parser = argparse.ArgumentParser(description="Plot results for Greedy Client FCFS analysis")
    parser.add_argument('--input', default='fairness_results.csv', help="Input CSV file with experiment results")
    parser.add_argument('--output', default='p3_plot.png', help="Output file for the plot")
    args = parser.parse_args()

    aggregated_results = load_and_aggregate_results(args.input)
    if aggregated_results:
        statistics = calculate_statistics(aggregated_results)
        create_jains_fairness_plot(statistics, args.output)

if __name__ == "__main__":
    main()
